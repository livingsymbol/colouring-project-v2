function findRowIn2DMatrix(matrix, target) {
    for (let i = 0; i < matrix.length; i++) {
        if (matrix[i].indexOf(target) !== -1) {
            return i; // Return the row index
        }
    }
    return -1; // Return -1 if the element is not found
}

